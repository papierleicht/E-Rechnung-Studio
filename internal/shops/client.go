const (
	shopifyVersion   = "2026-10"
	maxResponseBytes = 16 << 20
	maxPages         = 1000
)

var shopifyHost = regexp.MustCompile(`^[a-z0-9][a-z0-9-]*\.myshopify\.com$`)
var wixSiteID = regexp.MustCompile(`^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$`)

// Client only reads remote orders. Shopify POSTs contain GraphQL queries or
// request a short-lived access token; they never mutate store data.
type Client struct{ http *http.Client }

type clientError struct{ message string }

func (e *clientError) Error() string { return e.message }

// SafeError only exposes bounded messages generated by this client. It never
// forwards arbitrary fetcher, HTTP transport or remote response errors.
func SafeError(err error) string {
	var safe *clientError
	if errors.As(err, &safe) && len(safe.message) <= 1000 {
		return safe.message
	}
	return "Der Shop-Abruf ist fehlgeschlagen. Bitte Verbindung, Zugangsdaten und Leserechte prüfen."
}

func NewClient() *Client {
	return &Client{http: &http.Client{Timeout: 45 * time.Second, CheckRedirect: func(*http.Request, []*http.Request) error { return http.ErrUseLastResponse }}}
}

func NormalizeConnection(c Connection) (Connection, error) {
	c.Provider = strings.ToLower(strings.TrimSpace(c.Provider))
	switch c.Provider {
	case "shopify", "woocommerce", "shopware", "gambio", "wix", "prestashop":
	default:
		return c, errors.New("Bitte ein unterstütztes Shopsystem auswählen.")
	}
	c.SiteID = strings.ToLower(strings.TrimSpace(c.SiteID))
	if c.Provider == "wix" {
		if !wixSiteID.MatchString(c.SiteID) {
			return c, errors.New("Bitte eine gültige Wix-Website-ID (Site-ID) eingeben.")
		}
	} else if c.SiteID != "" {
		return c, errors.New("Eine Website-ID wird nur für Wix benötigt.")
	}
	c.Label = strings.TrimSpace(c.Label)
	raw := strings.TrimSpace(c.URL)
	if !strings.Contains(raw, "://") {
		raw = "https://" + raw
	}
	u, err := url.Parse(raw)
	if err != nil || u.Hostname() == "" || u.Scheme != "https" || u.User != nil || u.RawQuery != "" || u.ForceQuery || strings.Contains(raw, "#") || u.Opaque != "" {
		return c, errors.New("Bitte eine gültige HTTPS-Shop-URL ohne Zugangsdaten, Parameter oder Fragment eingeben.")
	}
	u.Host = strings.ToLower(u.Host)
	if u.Port() != "" && u.Port() != "443" {
		return c, errors.New("Die Shop-URL muss den HTTPS-Standardport verwenden.")
	}
	if c.Provider == "shopify" {
		if !shopifyHost.MatchString(u.Hostname()) || (u.Path != "" && u.Path != "/") {
			return c, errors.New("Bitte die Shopify-Adresse im Format https://mein-shop.myshopify.com eingeben.")
		}
		u.Path = ""
	} else {
		// WordPress may live in a subdirectory. Reject ambiguous encoded paths.
		if u.RawPath != "" || strings.Contains(u.Path, "\\") || strings.Contains(u.Path, "//") {
			return c, errors.New("Die Shop-URL enthält einen ungültigen Pfad.")
		}
		for _, segment := range strings.Split(u.Path, "/") {
			if segment == "." || segment == ".." {
				return c, errors.New("Die Shop-URL enthält einen ungültigen Pfad.")
			}
		}
		u.Path = strings.TrimRight(u.Path, "/")
	}
	u.Host = u.Hostname()
	if strings.Contains(u.Host, ":") {
		u.Host = "[" + u.Host + "]"
	}
	c.URL = u.String()
	if c.Label == "" {
		c.Label = u.Hostname()
	}
	return c, nil
}

func ValidateCredentials(provider string, c Credentials) error {
	valid := func(v string) bool {
		return strings.TrimSpace(v) != "" && !strings.ContainsAny(v, "\r\n\x00") && len(v) <= 8192
	}
	switch provider {
	case "shopify":
		if valid(c.AccessToken) || (strings.TrimSpace(c.AccessToken) == "" && valid(c.ClientID) && valid(c.ClientSecret)) {
			return nil
		}
		return errors.New("Bitte einen Shopify-Admin-API-Token oder Client-ID und Client-Secret eingeben.")
	case "woocommerce":
		if valid(c.ConsumerKey) && valid(c.ConsumerSecret) {
			return nil
		}
		return errors.New("Bitte WooCommerce Consumer Key und Consumer Secret mit Leserechten eingeben.")
	case "shopware":
		if valid(c.ClientID) && valid(c.ClientSecret) {
			return nil
		}
		return errors.New("Bitte die Shopware-Zugangs-ID und den Sicherheitsschlüssel der Integration eingeben.")
	case "gambio":
		if valid(c.Username) && valid(c.Password) && !strings.Contains(c.Username, ":") {
			return nil
		}
		return errors.New("Bitte den Gambio-API-Benutzernamen und das Passwort eingeben.")
	case "wix", "prestashop":
		if valid(c.APIKey) && (provider != "prestashop" || !strings.Contains(c.APIKey, ":")) {
			return nil
		}
		return errors.New("Bitte einen gültigen API-Schlüssel mit Lesezugriff auf Bestellungen eingeben.")
	default:
		return errors.New("Die Shop-Plattform wird nicht unterstützt.")
	}
}

func (c *Client) FetchOrders(ctx context.Context, conn Connection, credentials Credentials, since time.Time) (orders []Order, resultErr error) {
	defer func() {
		if resultErr != nil {
			resultErr = &clientError{message: resultErr.Error()}
		}
	}()
	conn, err := NormalizeConnection(conn)
	if err != nil {
		return nil, err
	}
	if err = ValidateCredentials(conn.Provider, credentials); err != nil {
		return nil, err
	}
	ctx, cancel := context.WithTimeout(ctx, 5*time.Minute)
	defer cancel()
	switch conn.Provider {
	case "shopify":
		orders, resultErr = c.fetchShopify(ctx, conn, credentials, since)
	case "woocommerce":
		orders, resultErr = c.fetchWoo(ctx, conn, credentials, since)
	case "shopware":
		orders, resultErr = c.fetchShopware(ctx, conn, credentials, since)
	case "gambio":
		orders, resultErr = c.fetchGambio(ctx, conn, credentials, since)
	case "prestashop":
		orders, resultErr = c.fetchPrestaShop(ctx, conn, credentials, since)
	case "wix":
		orders, resultErr = c.fetchWix(ctx, conn, credentials, since)
	}
	if ctx.Err() != nil {
		return nil, errors.New("Der Shop-Abruf wurde abgebrochen oder hat das Zeitlimit überschritten.")
	}
	return orders, resultErr
}

// API errors deliberately omit remote bodies, URLs and wrapped transport errors:
// a compromised endpoint can echo credentials in any of them.
func (c *Client) request(ctx context.Context, method, endpoint string, body []byte, headers map[string]string, credentials *Credentials, target any) (http.Header, error) {
	req, err := http.NewRequestWithContext(ctx, method, endpoint, bytes.NewReader(body))
	if err != nil {
		return nil, errors.New("Die Shop-Anfrage konnte nicht erstellt werden.")
	}
	for k, v := range headers {
		req.Header.Set(k, v)
	}
	req.Header.Set("Accept", "application/json")
	if credentials != nil {
		req.SetBasicAuth(credentials.ConsumerKey, credentials.ConsumerSecret)
	}
	res, err := c.http.Do(req)
	if err != nil {
		if ctx.Err() != nil {
			return nil, errors.New("Der Shop-Abruf wurde abgebrochen oder hat das Zeitlimit überschritten.")
		}
		return nil, errors.New("Der Shop ist nicht erreichbar. Bitte Verbindung und HTTPS-Adresse prüfen.")
	}
	defer res.Body.Close()
	if res.StatusCode < 200 || res.StatusCode >= 300 {
		return nil, fmt.Errorf("Der Shop hat den Abruf abgelehnt (HTTP %d). Bitte Zugangsdaten, Leserechte und Shop-Adresse prüfen.", res.StatusCode)
	}
	data, err := io.ReadAll(io.LimitReader(res.Body, maxResponseBytes+1))
	if err != nil || len(data) > maxResponseBytes {
		return nil, errors.New("Die Shop-Antwort ist unvollständig oder zu groß. Es wurden keine Bestellungen übernommen.")
	}
	decoder := json.NewDecoder(bytes.NewReader(data))
	decoder.UseNumber()
	if err = decoder.Decode(target); err != nil {
		return nil, errors.New("Der Shop hat eine ungültige Antwort gesendet. Es wurden keine Bestellungen übernommen.")
	}
	if decoder.Decode(new(any)) != io.EOF {
		return nil, errors.New("Der Shop hat eine ungültige Antwort gesendet.")
	}
	return res.Header, nil
}
